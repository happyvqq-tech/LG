// 影片推薦：給搜尋方向，不給具體影片
//
// ── 為什麼不讓 AI 推薦「某一支影片」 ────────────────────────
//
// 歌曲那邊可以推薦具體曲目，因為「Let It Be 是 The Beatles 唱的」是模型
// 記得住的常識。但 YouTube 影片不是——模型記不住哪支影片存在、標題叫什麼、
// 在哪個頻道。推薦一支不存在的影片比不推薦更糟：使用者去搜尋、找不到、
// 然後開始懷疑整個功能。
//
// 所以這支只做它真正可靠的事：**依程度與主題給出調校過的搜尋方向**，
// 再由 YouTube 搜尋把它變成真實存在的影片。頻道名稱可以提（那是穩定的
// 專有名詞，而且錯了使用者一搜就知道），但必須標示成「可能已改名或停更」。
//
// ── 選片標準跟選歌不一樣 ───────────────────────────────────
//
// 歌曲要挑「咬字清楚、重複率高」；影片要挑的是**真實但聽得下去**的語速。
// 太慢的教學影片（刻意放慢、字正腔圓）練不到真實聽力——那種語速現實中不存在。
// 太快的脫口秀又會讓人直接放棄。中間那條線才是這支要找的東西。

import type { Level, TaskLanguage } from './types'

export interface VideoPickerInput {
  language: TaskLanguage
  level: Level
  /** 使用者想看的主題（自由輸入） */
  topic: string
  /** 成員填的興趣與近況 */
  interests?: string
}

/** 各語言的真實素材長什麼樣、以及該避開什麼 */
const LANGUAGE_GUIDE: Record<TaskLanguage, string> = {
  英文:
    '英文的真實素材很多但難度落差極大。避開新聞主播（語速與用詞都不是日常對話）、' +
    '避開脫口秀與喜劇（語速過快且文化梗密集）、避開刻意放慢的教學影片（那種語速現實中不存在，練不到真實聽力）。' +
    '優先 vlog、訪談、podcast 的影片版、科普頻道——都是正常語速但有結構的內容。' +
    '腔調要分散：不要六個方向全是美式，英式、澳式、以及非母語者的國際英語都該出現',
  日文:
    '日文避開動畫（語速與角色語尾都不是真人講話方式，「〜のだ」「〜かしら」現實中沒人這樣說）、' +
    '避開新聞（です・ます 的書面腔）。優先 vlog、對談、料理與旅遊實況——' +
    '那裡才有真正的普通体、省略、以及「なんか」「まあ」「〜じゃん」這類課本不教的口語',
  韓文:
    '韓文避開偶像綜藝（語速快、字幕特效多、流行語密集）、避開新聞。' +
    '優先 vlog、Q&A、料理與開箱——那裡有正常語速的해요体與真實的縮讀',
}

export function videoPickerSystemPrompt(input: VideoPickerInput): string {
  const interests = input.interests?.trim()

  return `你是語言教師，正在替學習者規劃「用 YouTube 真實影片學${input.language}」。

輸入變數：
- 語言：${input.language}
- 程度：${input.level}
- 想看的主題：${input.topic}
- 學習者的興趣與近況：${interests && interests.length > 0 ? interests : '未提供'}

最高原則：**不要推薦具體的影片。**
你記不住哪支 YouTube 影片存在、標題叫什麼。推薦一支不存在的影片比不推薦更糟——
使用者搜不到就會不信任整個功能。你的工作是給**搜尋方向**，
由系統拿去 YouTube 搜出真實存在的影片。

硬性要求：
1. 給 6 個搜尋方向。每個包含：
   - query：直接可以貼進 YouTube 搜尋框的字串（用${input.language}寫，不要用中文）
   - label：一句中文說明這是什麼類型的內容
   - why：為什麼適合 ${input.level}，要具體（例如「對談形式，語速正常但有停頓可以跟上」），
     不要寫「內容豐富、適合學習」這種沒有資訊的話
   - caution：這類內容難在哪。每個都要寫，沒有缺點的素材不存在
   - minutes：建議的片長範圍，例如「5-10 分鐘」
2. **真實但聽得下去**才是選片標準。刻意放慢、字正腔圓的教學影片要避開——
   那種語速現實中不存在，練了也遷移不到真實場合。${LANGUAGE_GUIDE[input.language]}
3. 程度調整：A2／B1 偏向有畫面輔助理解的內容（料理、開箱、旅遊實況——
   看得到東西就算漏聽幾個字也接得下去）；B2／C1 可以挑純對談與論述
4. 六個方向要分散：內容類型、說話人數（獨白／對談）、腔調都不要重複
5. 可以在 query 裡帶上穩定的頻道名稱，但要在 caution 註明「頻道可能已改名或停更」
${interests && interests.length > 0 ? '6. 盡量貼近學習者的興趣，但「聽得下去」仍優先於投其所好' : ''}

只輸出 JSON，不加任何前言、不用 markdown 圍欄：
{
  "picks": [
    {
      "query": "",
      "label": "",
      "why": "",
      "caution": "",
      "minutes": ""
    }
  ]
}`
}
