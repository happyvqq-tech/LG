// 日文語體（普通体／丁寧体）的統一規則
//
// 為什麼要有這支：原本 taskGenerator、extensive、vocabEnrich、quizGenerator
// 四個地方各自寫死「用丁寧體」，結果整個 App 產出的日文都是です・ます。
// 那不是日本人平常講話的樣子，也不是學習者最該先掌握的東西。
//
// ── 為什麼普通体才是地基 ──────────────────────────────────
//
// 1. 所有中高級文型都接在普通形上：〜と思う、〜かもしれない、〜つもりだ、
//    〜のに、〜なら、以及連体修飾（關係子句）。只練ます形的人到了中級，
//    每個句子都得先把「買います」逆推回「買う」才能往下接——而逆推需要
//    知道動詞分類，正推是機械的。等於把難的放前面、簡單的放後面。
// 2. 真實輸入九成不是丁寧体：動畫、日劇、YouTube、小說、朋友對話都是普通体，
//    報紙與論文是である体。只受過丁寧体訓練的人打開任何真材實料都聽不懂。
//
// ── 但不能廢掉丁寧体 ─────────────────────────────────────
//
// 對店員、陌生人、上司用普通体是真的失禮。真正要練的能力不是「選一個」，
// 是「切換」——讀出關係（上下／內外／親疏）再選語體。中文沒有對應的機制，
// 所以要靠情境刻意練，而不是設一個全域預設值。
//
// ── 敬語（尊敬語／謙譲語）不在這裡 ───────────────────────
//
// 外國人九成的敬語遭遇是被動的（いらっしゃいませ／少々お待ちください／
// ご覧ください）。聽不懂會誤事，但要正確產出謙譲語很難，連日本人都常錯。
// 所以敬語應該是後期的、接收優先的獨立模組，不該混進日常任務裡。

