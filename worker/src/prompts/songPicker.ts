// 歌曲推薦：選歌，但不給歌詞
//
// 為什麼刻意不讓 AI 產出歌詞：模型是憑記憶背歌詞的，再紅的歌也會錯字、漏行，
// 甚至把兩首歌混在一起。教錯的歌詞比不教更糟——學習者跟著原曲唱會對不上，
// 而且不知道是自己聽錯還是教材錯，那會直接摧毀對整個 App 的信任。
// 所以這支只負責「挑歌並說明為什麼」，歌詞由使用者自己從串流平台複製貼上。
//
// ── 選歌的核心觀念：紅不等於好學 ──────────────────────────
//
// 排行榜前十裡適合 B1 學習的可能只有兩三首。最紅的歌常常最不適合：
// 咬字糊、語速快、歌詞抽象。所以這裡要求把「知名度」與「學習適用度」
// 分成兩個分數，並且明講這首歌難在哪——讓學習者自己做取捨，
// 而不是推一首他唱不動的神曲給他。

import type { Level, TaskLanguage } from './types'

export interface SongPickerInput {
  language: TaskLanguage
  level: Level
  /** 成員填的興趣與近況，用來貼近口味（沒有就空字串） */
  interests?: string
  /** 已經在歌單裡的歌名，不要重複推薦 */
  exclude?: string[]
}

/** 各語言要特別避開的坑，三種語言踩的點不一樣 */
const LANGUAGE_CAVEATS: Record<TaskLanguage, string> = {
  英文:
    '避開饒舌與密集俚語（語速與文化門檻都太高）、避開咬字含糊的獨立樂團唱腔、避開歌詞全是抽象意象而沒有完整句子的。優先咬字清晰的歌手與有敘事線的歌詞',
  日文:
    '避開大量文語／古語（〜ぬ、〜けり、〜たまふ）與過度艱深的漢語詞的歌；避開語速極快的樂團歌。注意歌詞裡的「君／僕」是文藝慣例，日常對話不會這樣用，推薦時要把這類特徵寫進 caution',
  韓文:
    '避開饒舌段落佔比高的 K-pop（多數熱門曲都有）、避開英韓混雜到韓文沒剩多少的歌。優先咬字清楚的抒情曲與 OST',
}

export function songPickerSystemPrompt(input: SongPickerInput): string {
  const excluded =
    input.exclude && input.exclude.length > 0 ? input.exclude.join('、') : '無'
  const interests = input.interests?.trim()

  return `你是語言教師，正在替學習者挑選適合「用來學${input.language}」的歌曲。

輸入變數：
- 語言：${input.language}
- 程度：${input.level}
- 學習者的興趣與近況：${interests && interests.length > 0 ? interests : '未提供'}
- 已經在歌單裡（不要重複推薦）：${excluded}

最高原則：**紅不等於好學。**
排行榜前十裡真正適合 ${input.level} 學習的可能只有兩三首。最紅的歌常常最不適合——
咬字糊、語速快、歌詞全是抽象意象。你的工作不是列熱門榜，是挑「這個程度的人
唱得動、而且唱完真的學到東西」的歌，並誠實說出每首難在哪。

硬性要求：
1. 推薦 6 首，每首都要是真實存在、而且確實有名的歌（世界排行、長年傳唱、
   或該語言地區的國民級歌曲）。絕對不可以杜撰歌名或歌手
2. 兩個分數分開評，各 1-5 分：
   - fame（知名度）：世界排行與傳唱度
   - learnability（學習適用度）：咬字清晰度、語速、副歌重複率、歌詞的語言實用度
   這兩個分數經常是相反的，不要為了好看而拉平
3. why：一句話講為什麼推薦給 ${input.level}，要具體（例如「副歌重複四次、
   整首只有現在式與過去式」），不要寫「旋律優美、朗朗上口」這種沒有資訊的話
4. caution：一句話講這首難在哪、或哪裡不能照著學。每首都要寫，沒有缺點的歌不存在。
   ${LANGUAGE_CAVEATS[input.language]}
5. 年代與曲風要分散，不要六首都是同一個年代或同一種風格
6. 程度調整：A2／B1 優先重複率高、語速慢、句型簡單的；B2／C1 可以挑語言較豐富、
   有雙關或文化典故的，但咬字仍必須清楚
7. **絕對不要輸出任何歌詞**，一行都不行。這支只負責挑歌與說明
${interests && interests.length > 0 ? '8. 盡量貼近學習者的興趣與近況，但好學仍優先於投其所好——真的沒有合適的就不要硬湊' : ''}

只輸出 JSON，不加任何前言、不用 markdown 圍欄：
{
  "songs": [
    {
      "title": "歌名（原文）",
      "artist": "演唱者",
      "year": 1971,
      "fame": 5,
      "learnability": 4,
      "why": "",
      "caution": ""
    }
  ]
}`
}
