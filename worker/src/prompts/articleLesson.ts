// 真實文章的分析層：回答「為什麼這篇你讀不動」
//
// ── 三個教材模組各自回答不同的問題 ─────────────────────────
//
//   歌曲：這句能不能拿去用（旋律會為了押韻與音節數扭曲語言）
//   影片：為什麼你聽不懂（連音、脫落、填充詞）
//   文章：**為什麼你讀不動**
//
// 讀不動的原因幾乎從來不是生字——查一下就知道了。真正卡住人的是：
//
// 1. 一句話套三層子句。學習者讀到第二個逗號就忘了主詞是誰，
//    不是不懂每個詞，是組不回那棵樹。這是 B1 → B2 最大的那道牆
// 2. 指涉斷掉。「該公司」「同氏」「해당 사건」指的是前面哪一個？
//    中文母語者習慣省略主詞，對英日韓這種會用定指回指的語言特別容易斷
// 3. 書面語的詞彙層。implement／実施する／실시하다 這些字認得，
//    但不知道「講話時不會這樣說」，於是學起來變成一張書面腔的嘴
// 4. 邏輯連接詞。however／一方で／반면——論述的骨架靠它們撐，
//    漏掉一個，整段的立場就讀反了
//
// 所以這支的輸出重心是上面四件事。**刻意不做逐句翻譯**：
// 給了對照譯文，眼睛就直接吃中文，原文等於沒讀。

import type { Level, TaskLanguage } from './types'

export interface ArticleLessonInput {
  language: TaskLanguage
  level: Level
  title: string
  /** 使用者貼上或由 Worker 抓回來的文章原文 */
  text: string
}

/** 各語言「書面語之所以難」的具體長相 */
const WRITTEN_GUIDE: Record<TaskLanguage, string> = {
  英文:
    '名詞化（the implementation of the policy ← they implemented the policy）、' +
    '被動語態、關係子句與分詞構句疊套、以及拉丁語源的正式用字' +
    '（investigate／look into、purchase／buy、sufficient／enough）。' +
    '口語版本多半是把名詞化拆回動詞、把被動改回主動、把長句切成兩三句',
  日文:
    '長い連体修飾節（「〜という」で名詞に繋ぐ）、漢語サ変動詞（実施する・検討する）、' +
    'だ・である体、受身と使役受身、そして「〜に伴い」「〜をめぐり」「〜とみられる」' +
    'といった書き言葉専用の接続・文末。話し言葉版は和語動詞に戻し（実施する→やる）、' +
    '修飾節を切り離して二文にするのが基本',
  韓文:
    '관형사형 어미로 길게 수식하는 구조（-는/-(으)ㄴ/-(으)ㄹ）、한자어 명사화（실시·검토·방안）、' +
    '-(으)며·-(으)로써·-(이)라는 등 문어체 연결어미、그리고 하다체 종결. ' +
    '구어판은 한자어를 고유어로 풀고（실시하다→하다）, 긴 수식절을 끊어 두 문장으로',
}

export function articleLessonSystemPrompt(input: ArticleLessonInput): string {
  return `你是語言教師，正在把一篇真實的${input.language}文章做成閱讀教材。

輸入變數：
- 語言：${input.language}
- 學習者程度：${input.level}
- 文章標題：${input.title}

以下是文章原文：
"""
${input.text}
"""

最高原則（優先於下面所有要求）：
**原文就是唯一的事實來源，一個字都不要改、不要補、不要重寫。**
你的工作是分析，不是創作。所有引用都必須是原文裡逐字存在的片段——
憑印象改寫過的引用會讓學習者在文章裡找不到那一句，整份教材就失去依據。

**不要做逐句翻譯。** 給了對照譯文，學習者的眼睛會直接吃中文，原文等於沒讀。
需要解釋的地方用中文說明「這裡在做什麼」，不是把它翻出來。

這份教材要回答的是：**為什麼這篇你讀不動。**
讀不動幾乎從來不是生字的問題——查一下就知道了。真正卡住人的是下面四件事。

硬性要求：

1. gist：兩三句話說這篇在講什麼。有了脈絡才讀得進細節

2. register：一句話說這篇的文體（硬新聞、評論、特稿、散文）以及它的語氣，
   讓學習者知道自己在讀的是哪一種${input.language}

3. sentences（長句解剖）：挑 2-4 個**最難拆的長句**，每句給
   - original：原文照抄，一字不改
   - backbone：把修飾全部拿掉之後剩下的骨幹（主詞＋動詞＋受詞），
     用${input.language}寫，不是中文翻譯
   - note：一句中文說明難在哪（第幾層子句、哪個詞是先行詞、哪裡省略了關係代名詞）
   **這一項是整份教材最重要的部分**——讀不動長文，九成是組不回這棵樹

4. refs（指涉鏈）：挑 2-5 個回指，說明它指的是前面的哪一個。
   「該公司」「同氏」「the measure」「해당 사건」這類。
   中文習慣省略主詞，所以台灣學習者對這種定指回指特別容易斷線。
   pointer 寫原文裡的那個詞，refers_to 寫它實際指向的對象（也用原文的說法）

5. spoken（書面 → 口語）：挑 3-5 句，寫出「同樣的意思，你會怎麼用講的說」。
   written 照抄原文片段，said 寫口語版，note 一句話說明換掉了什麼。
   ${input.language}的書面語特徵是：${WRITTEN_GUIDE[input.language]}
   這一項是把「讀」接回「說」的橋——只讀不轉換的人會長出一張書面腔的嘴

6. connectives：這篇用到的邏輯連接詞，2-5 個。word 寫原文裡的詞，
   role 用中文說它在做什麼（轉折／因果／讓步／舉例／補充）。
   漏讀一個連接詞，整段的立場就會讀反

7. chunks：2-4 個可以整段帶走的語塊，**必須逐字出現在原文裡**

只輸出 JSON，不加任何前言、不用 markdown 圍欄：
{
  "gist": "",
  "register": "",
  "sentences": [{"original": "", "backbone": "", "note": ""}],
  "refs": [{"pointer": "", "refers_to": ""}],
  "spoken": [{"written": "", "said": "", "note": ""}],
  "connectives": [{"word": "", "role": ""}],
  "chunks": [{"text": "", "zh": "", "usage": ""}]
}`
}
