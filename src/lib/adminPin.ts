// 單字庫、測驗成績、古文進度、連續天數全部 cascade 一起消失，而且沒有復原
// 按鈕。這種操作需要一道「要知道才過得去」的門檻，而不是再按一次「確定」。

const ADMIN_PIN = '0854'

export function isAdminPin(input: string): boolean {
  return input.trim() === ADMIN_PIN
}

